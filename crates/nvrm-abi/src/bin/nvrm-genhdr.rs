#[cfg(test)]
mod tests {
    use super::generate;

    /// Field names of `nvrm_req`, in the order `generate()` emits them.
    /// The guest module writes into every one of these by name, so a
    /// missing row is a compile error over there and nothing here -- see
    /// the WARNING at `aux_fd_field_proc`: a dropped row leaves the struct
    /// the same 160 bytes and every size and offset assert still passes.
    const REQ_FIELDS: &[&str] = &[
        "seq", "kind", "dev_tag", "ioctl_nr", "target_token", "inline_len", "aux_len",
        "fd_field_off", "fd_field_proc", "fd_field_token", "embedded_ptr_off", "nested_count",
        "nested", "aux_fd_field_off", "aux_fd_field_proc", "aux_fd_field_token", "map_len",
        "addr", "gpa_run_count", "guest_proc",
    ];

    /// The output is a C header that goes into a Linux kernel module tree
    /// and is compiled by the guest's kernel build. It must be plain ASCII:
    /// a stray UTF-8 dash or quote copied out of a Rust doc comment into
    /// one of the string literals here would end up in a checked-in kernel
    /// header, where it is at best a warning and at worst a broken build in
    /// a place nobody looks.
    #[test]
    fn the_generated_header_is_pure_ascii() {
        let text = generate();
        assert!(!text.is_empty());
        for (i, b) in text.bytes().enumerate() {
            assert!(
                b.is_ascii(),
                "byte {i} is {b:#x}, not ASCII: {:?}",
                &text[i.saturating_sub(40)..(i + 1).min(text.len())]
            );
        }
    }

    /// Every field of the wire request carries its own
    /// `_Static_assert(offsetof(...))` in the header. That assert is the
    /// entire mechanism by which the C module cannot be built against a
    /// layout that has drifted from the Rust `Req` -- one field without a
    /// line is one field whose offset nothing checks.
    #[test]
    fn every_request_field_has_an_offset_assert() {
        let text = generate();
        for field in REQ_FIELDS {
            let needle = format!("_Static_assert(offsetof(struct nvrm_req, {field}) == ");
            assert_eq!(
                text.matches(&needle).count(),
                1,
                "expected exactly one offset assert for nvrm_req.{field}"
            );
        }
        // And no field beyond the list above: a new one added to `Req`
        // without a row here would go unnoticed otherwise.
        assert_eq!(
            text.matches("_Static_assert(offsetof(struct nvrm_req, ").count(),
            REQ_FIELDS.len(),
            "the number of nvrm_req offset asserts changed"
        );
    }

    /// The protocol version is the first thing host and guest compare (the
    /// Hello carries it), and it is emitted as a tab-separated `#define`
    /// the module includes. Both the number and the spelling are pinned:
    /// the module's `#if NVRM_PROTO_VERSION != ...` is a textual match.
    #[test]
    fn the_header_defines_the_protocol_version() {
        let text = generate();
        assert!(
            text.contains("#define NVRM_PROTO_VERSION\t6u"),
            "the header must define NVRM_PROTO_VERSION as 6u"
        );
        assert_eq!(nvrm_wire::PROTO_VERSION, 6, "the constant this is generated from");
    }

    /// Two calls produce byte-identical output. `nvrm-genhdr --check`
    /// compares the checked-in header against a fresh run and fails the
    /// build on any difference, so anything non-deterministic in here (a
    /// timestamp, a hash-map iteration order) would make that check fail at
    /// random.
    #[test]
    fn generation_is_deterministic() {
        assert_eq!(generate(), generate());
    }
}
